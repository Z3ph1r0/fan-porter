def normalize(lang: str) -> str:
    return lang if lang in LANGS else "en"


def lang_name(lang: str) -> str:
    return NAMES[normalize(lang)]


def tr(lang: str, key: str) -> str:
    chosen = TEXT.get(normalize(lang)) or TEXT["en"]
    if key in chosen:
        return chosen[key]
    return TEXT["en"].get(key, key)
